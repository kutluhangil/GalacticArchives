// Provenance for the shipped lore. Every body and character carries the
// Wookieepedia article it was sourced from, which of that article's infobox
// fields this app consumes, and — the honest part — which headline fields the
// article defines no value for at all.
//
// That last distinction is why this module exists: an empty Diameter row can
// mean two very different things, and the panel should not conflate them.
//
//   sourced   the article's infobox states it            -> show the value
//   authored  we summarised it; the infobox states none  -> show it, marked
//   unstated  the infobox states none and we have none   -> say so
//   gap       the infobox states it and we have none     -> nothing yet
//
// sources.json is regenerated by scripts/sync-sources.mjs from a fresh digest.

import sourcesJson from '../data/sources.json'

export interface SourceEntry {
  /** "wookieepedia:<article title>" */
  source: string
  url?: string
  /** headline fields the article's infobox defines no value for */
  unverified?: string[]
  note?: string
}

/** the headline fields the panel reports on; named as the infobox names them */
export type TrackedField = 'diameter' | 'population' | 'government'

interface SourcesFile {
  generatedAt: string
  method: string
  notes: Record<string, string>
  entities: Record<string, SourceEntry>
}

const file = sourcesJson as unknown as SourcesFile

export const sourcesGeneratedAt = file.generatedAt
export const sourceNotes = file.notes

export function sourceFor(id: string): SourceEntry | undefined {
  return file.entities[id]
}

/** "wookieepedia:Mos Eisley" -> the article's url. POIs carry their source
 *  inline (see Poi.source) because a location is sourced per place, not per
 *  world. */
export function articleUrl(source: string): string {
  return `https://starwars.fandom.com/wiki/${source.replace(/^wookieepedia:/, '').replace(/ /g, '_')}`
}

/** true when the sourced article's infobox defines no value for `field` */
export function isUnstatedInCanon(id: string, field: TrackedField): boolean {
  return file.entities[id]?.unverified?.includes(field) ?? false
}

/** How a value the panel is about to show was arrived at. `undefined` when the
 *  body has no source entry at all, which validate-lore rejects. */
export function provenance(
  id: string,
  field: TrackedField,
  hasValue: boolean,
): 'sourced' | 'authored' | 'unstated' | 'gap' | undefined {
  const entry = file.entities[id]
  if (!entry) return undefined
  const unstated = entry.unverified?.includes(field) ?? false
  if (hasValue) return unstated ? 'authored' : 'sourced'
  return unstated ? 'unstated' : 'gap'
}
